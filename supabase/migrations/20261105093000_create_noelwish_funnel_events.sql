create table if not exists public.noelwish_funnel_events (
  id bigint generated by default as identity primary key,
  event_id text not null unique,
  event_name text not null,
  occurred_at timestamptz not null default now(),
  received_at timestamptz not null default now(),
  visitor_id text,
  session_id text,
  flow_id text,
  page_path text,
  page_hash text,
  referrer_host text,
  language text,
  market text,
  currency text,
  device_type text,
  product_id text,
  stage text,
  stage_sequence integer,
  duration_seconds integer,
  amount_minor bigint,
  stripe_session_id text,
  metadata jsonb not null default '{}'::jsonb,
  constraint noelwish_funnel_event_name_length check (char_length(event_name) between 1 and 40),
  constraint noelwish_funnel_duration_nonnegative check (duration_seconds is null or duration_seconds >= 0),
  constraint noelwish_funnel_amount_nonnegative check (amount_minor is null or amount_minor >= 0)
);

create index if not exists noelwish_funnel_events_occurred_at_idx
  on public.noelwish_funnel_events (occurred_at desc);
create index if not exists noelwish_funnel_events_name_occurred_idx
  on public.noelwish_funnel_events (event_name, occurred_at desc);
create index if not exists noelwish_funnel_events_session_idx
  on public.noelwish_funnel_events (session_id, occurred_at);
create index if not exists noelwish_funnel_events_flow_idx
  on public.noelwish_funnel_events (flow_id, occurred_at)
  where flow_id is not null;

alter table public.noelwish_funnel_events enable row level security;
revoke all on table public.noelwish_funnel_events from anon, authenticated;
revoke all on sequence public.noelwish_funnel_events_id_seq from anon, authenticated;
grant select, insert on table public.noelwish_funnel_events to service_role;
grant usage, select on sequence public.noelwish_funnel_events_id_seq to service_role;
